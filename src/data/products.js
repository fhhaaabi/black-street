function build(row, k) {
  const [
    name,
    category,
    sizeType,
    shape,
    style,
    price,
    old,
    cols,
    description,
    feats,
    tags,
    featured,
    popularity,
    days,
    customSizes,
  ] = row;
  const slug = slugify(name);
  const pkey = PHOTO_PREFIX[`${shape}:${style}`] ? `${shape}:${style}` : shape;
  const prefix = PHOTO_PREFIX[pkey] || "p";
  counters[prefix] = (counters[prefix] || 0) + 1;
  const code = prefix + counters[prefix]; // ex : t1, t2, pt1, bag1
  const shared =
    (PHOTO_MODE === "single" && !PER_COLOR_PRODUCTS.includes(slug)) ||
    SINGLE_PHOTO_PRODUCTS.includes(slug);
  const labels = customSizes
    ? customSizes.split(",")
    : sizeType === "shoes"
      ? SHOES
      : sizeType === "clothing"
        ? shape === "pants" && style !== "short"
          ? WAIST
          : CLOTHES
        : [];
  let colors = cols.split(",").map((id, j) => {
    const [cname, hex] = COLORS[id];
    const c = {
      id,
      name: cname,
      hex,
      images: shared
        ? sharedImages(slug, k, code)
        : colorImages(slug, id, code),
      sizes: [],
    };
    if (labels.length) {
      c.sizes = labels.map((label, i) => {
        if ((k + j + i) % 9 === 0) return { label, stock: 0 };
        if ((k + j + i) % 11 === 0) return { label, stock: 3 + ((k + j) % 6) };
        return { label };
      });
    } else if (j > 0 && (k + j) % 6 === 0) c.stock = 0;
    else if ((k + j) % 4 === 0) c.stock = 2 + j;
    return c;
  });
  if (!COLOR_CHOICE) {
    // Pas de choix de couleur : une seule « variante » sans nom, avec les photos du produit
    const first = colors[0];
    const gallery = PER_COLOR_PRODUCTS.includes(slug)
      ? colors.flatMap((c) => colorImages(slug, c.id, code))
      : sharedImages(slug, k, code);
    colors = [
      {
        id: "unique",
        name: "",
        hex: "#8a8d91",
        images: gallery,
        sizes: first.sizes,
        ...(first.stock !== undefined ? { stock: first.stock } : {}),
      },
    ];
  }
  return {
    id: "p" + String(k + 1).padStart(2, "0"),
    slug,
    name,
    category,
    sizeType,
    description,
    price,
    ...(old ? { oldPrice: old } : {}),
    features: feats.split("|"),
    tags: tags.split(","),
    sharedPhotos: shared || !COLOR_CHOICE,
    colorChoice: COLOR_CHOICE,
    photoCode: code,
    featured: !!featured,
    popularity,
    createdAt: daysAgo(days),
    illustration: { shape, style },
    colors,
  };
}
export const products = rows.filter(Array.isArray).map(build);
export const getProductBySlug = (slug) =>
  products.find((p) => p && p.slug === slug) || null;
export const getProductById = (id) =>
  products.find((p) => p && p.id === id) || null;
